#!/usr/bin/env node
// Generates supabase/seed_phase3_challenges.sql from lib/seed-data/phase3-challenges.mjs
// — the single source of truth also used by app/dev/seed-validation/page.js.
// Run with: node scripts/generate-seed-sql.mjs

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { CHALLENGES } from "../lib/seed-data/phase3-challenges.mjs";
import { BATCH2 } from "../lib/seed-data/batch2-challenges.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// Dollar-quoting sidesteps every single-quote-escaping mistake (we've
// already been bitten by this once with '' vs \' in the Phase 1 seed file).
// The tag is checked against the content so a literal $$ in a challenge
// can't silently terminate the string early.
function dollarQuote(text) {
  if (String(text).includes("$$")) {
    throw new Error(`Content contains $$, which would break dollar quoting: ${String(text).slice(0, 80)}`);
  }
  return `$$${text}$$`;
}

function challengeToSql(challenge) {
  const {
    title,
    language,
    bug_category,
    difficulty,
    function_name,
    broken_code,
    correct_code,
    problem_description,
    symptom_description,
    explanation,
    test_cases,
    hints,
  } = challenge;

  const hintInserts = hints
    .map(
      (hintText, index) =>
        `select id, ${index + 1}, ${dollarQuote(hintText)} from new_challenge`
    )
    .join("\nunion all\n");

  return `with new_challenge as (
  insert into public.bug_challenges (
    title, language, bug_category, difficulty, function_name,
    broken_code, correct_code, problem_description, symptom_description,
    explanation, test_cases, status
  ) values (
    ${dollarQuote(title)},
    ${dollarQuote(language)},
    ${dollarQuote(bug_category)},
    ${dollarQuote(difficulty)},
    ${dollarQuote(function_name)},
    ${dollarQuote(broken_code)},
    ${dollarQuote(correct_code)},
    ${dollarQuote(problem_description)},
    ${dollarQuote(symptom_description)},
    ${dollarQuote(explanation)},
    ${dollarQuote(JSON.stringify(test_cases))}::jsonb,
    'published'
  )
  returning id
)
insert into public.hints (bug_challenge_id, hint_order, hint_text)
${hintInserts};`;
}

async function emit({ challenges, file, note }) {
  const toInsert = challenges.filter((c) => !c.alreadySeeded);
  const outputPath = path.join(__dirname, "..", "supabase", file);

  const header = `-- Generated by scripts/generate-seed-sql.mjs — do not hand-edit.
-- Change the source data in lib/seed-data/ and regenerate instead.
-- Run in the Supabase SQL Editor after migrations 0001, 0002 and 0003.
-- ${note}
-- Every challenge here was executed and verified by
-- scripts/verify-challenges.mjs before being generated.
`;

  const body = toInsert.map(challengeToSql).join("\n\n");
  await writeFile(outputPath, `${header}\n${body}\n`, "utf8");
  console.log(`Wrote ${toInsert.length} challenges to ${path.relative(process.cwd(), outputPath)}`);
}

await emit({
  challenges: CHALLENGES,
  file: "seed_phase3_challenges.sql",
  note: "Original batch. Skips the two already seeded in Phase 1.",
});

await emit({
  challenges: BATCH2,
  file: "seed_batch2_challenges.sql",
  note: "Second batch: 30 challenges, four per bug category.",
});
